import { createHash } from 'node:crypto';
import { createReadStream, createWriteStream, type ReadStream } from 'node:fs';
import { mkdir, rename, rm, stat } from 'node:fs/promises';
import path from 'node:path';
import { once } from 'node:events';
import { env } from '../config/env';

export interface StoredFile {
  bytes: number;
  sha256: string;
}

export interface FileWriter {
  write(chunk: string): Promise<void>;
  /** Flushes and publishes the file atomically; returns its size and checksum. */
  finish(): Promise<StoredFile>;
  /** Discards a partial file. Safe to call after a failure. */
  abort(): Promise<void>;
}

/**
 * Where generated files live. Only this interface is used by the export code, so moving to S3/GCS
 * means adding another implementation, not touching callers.
 */
export interface FileStore {
  open(key: string): Promise<FileWriter>;
  read(key: string): ReadStream;
  size(key: string): Promise<number>;
  remove(key: string): Promise<void>;
}

/** Keys are generated by the server, but are validated anyway so a bug can never escape the root directory. */
const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9_\-/.]*$/;

export class LocalFileStore implements FileStore {
  private readonly root: string;
  constructor(root: string) {
    this.root = path.resolve(root);
  }

  private resolve(key: string): string {
    if (!SAFE_KEY.test(key) || key.includes('..') || key.includes('//')) throw new Error('Invalid storage key');
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }

  async open(key: string): Promise<FileWriter> {
    const finalPath = this.resolve(key);
    const tmpPath = `${finalPath}.part`;
    await mkdir(path.dirname(finalPath), { recursive: true });
    const out = createWriteStream(tmpPath, { flags: 'w', mode: 0o600 }); // owner-only: exports contain patient data
    const hash = createHash('sha256');
    let bytes = 0;
    let closed = false;

    return {
      write: async (chunk) => {
        const buf = Buffer.from(chunk, 'utf8');
        hash.update(buf);
        bytes += buf.length;
        if (!out.write(buf)) await once(out, 'drain'); // respect backpressure
      },
      finish: async () => {
        out.end();
        await once(out, 'finish');
        closed = true;
        await rename(tmpPath, finalPath); // readers never see a half-written file
        return { bytes, sha256: hash.digest('hex') };
      },
      abort: async () => {
        if (!closed) {
          out.destroy();
          closed = true;
        }
        await rm(tmpPath, { force: true });
      },
    };
  }

  read(key: string): ReadStream {
    return createReadStream(this.resolve(key));
  }

  async size(key: string): Promise<number> {
    return (await stat(this.resolve(key))).size;
  }

  async remove(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

let store: FileStore | undefined;
export function getFileStore(): FileStore {
  store ??= new LocalFileStore(env.EXPORT_DIR);
  return store;
}
/** Test hook. */
export function setFileStore(s: FileStore | undefined) {
  store = s;
}
